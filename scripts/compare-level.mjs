// Puts one level's traces side by side for the write-up. It describes each run; with one run
// per condition, a difference here can't be credited to the harness alone.
//
// usage: node compare-level.mjs <level> [kind]      kind defaults to "run"
// Reads results/levels.csv and runs/task-a/<run>/; writes results/level-<level>-comparison.md.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

// kind can list several, such as "pilot,run", when a pilot was kept as a condition's run.
const [level, kind = "run"] = process.argv.slice(2)
const kinds = kind.split(",")
const lab = join(dirname(fileURLToPath(import.meta.url)), "..")

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ""
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const char = text[i]
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') {
        field += '"'
        i++
      } else if (char === '"') quoted = false
      else field += char
    } else if (char === '"') quoted = true
    else if (char === ",") {
      row.push(field)
      field = ""
    } else if (char === "\n") {
      row.push(field.replace(/\r$/, ""))
      rows.push(row)
      row = []
      field = ""
    } else field += char
  }
  if (field || row.length) rows.push([...row, field])
  const [header, ...body] = rows
  return body.filter((cells) => cells.length > 1).map((cells) => Object.fromEntries(header.map((name, index) => [name, cells[index]])))
}

const stripBom = (text) => text.replace(/^﻿/, "")
const facts = parseCsv(stripBom(readFileSync(join(lab, "results", "levels.csv"), "utf8"))).filter((row) => row.level === level && kinds.includes(row.kind))

// The newest run of each condition.
const latest = new Map()
for (const row of facts) latest.set(row.condition, row)
const order = ["claude", "opencode", "codex"].filter((name) => latest.has(name))
if (!order.length) throw new Error(`No rows for level ${level} with kind ${kind} in results/levels.csv.`)

const runs = order.map((condition) => {
  const row = latest.get(condition)
  const dir = join(lab, "runs", "task-a", row.run_id)
  const summary = JSON.parse(readFileSync(join(dir, "trace", "summary.json"), "utf8"))
  const files = parseCsv(stripBom(readFileSync(join(dir, "trace", "files.csv"), "utf8")))
  const hidden = existsSync(join(dir, "hidden-tests.txt")) ? readFileSync(join(dir, "hidden-tests.txt"), "utf8") : ""
  const failing = [...hidden.matchAll(/^not ok \d+ - (.+)$/gm)].map((match) => match[1].trim())
  return { condition, row, summary, files, failing, dir }
})

// Each harness counts reasoning differently: Codex's is part of its output count, OpenCode's
// is on top of its output count, and Claude Code's result doesn't separate it.
function reasoningTokens(run) {
  if (run.condition === "codex") {
    const lines = readFileSync(join(run.dir, "transcript.jsonl"), "utf8").split(/\r?\n/).filter(Boolean)
    const done = lines.map((line) => JSON.parse(line)).find((event) => event.type === "turn.completed")
    return `${done?.usage?.reasoning_output_tokens ?? "?"} (within output)`
  }
  if (run.condition === "opencode") {
    const name = readdirSync(run.dir).find((file) => /^session-.*\.json$/.test(file))
    return `${JSON.parse(stripBom(readFileSync(join(run.dir, name), "utf8"))).info?.tokens?.reasoning ?? "?"} (on top of output)`
  }
  return "not separated"
}

const table = (rows) => {
  const out = [`| ${rows[0].join(" | ")} |`, `|${rows[0].map(() => "---").join("|")}|`]
  for (const row of rows.slice(1)) out.push(`| ${row.map((cell) => String(cell ?? "").replaceAll("|", "\\|")).join(" | ")} |`)
  return out.join("\n")
}
const across = (label, value) => [label, ...runs.map(value)]
const head = ["", ...order]
const list = (values) => (values?.length ? values.join(", ") : "none")
const money = (value) => (value === "" || value == null ? "" : `$${Number(value).toFixed(2)}`)

const lines = [
  `# Level ${level}: what each run did`,
  "",
  `Generated by \`scripts/compare-level.mjs\` from each run's trace. One run per condition (kind: ${kind}), so this describes what happened and doesn't rank the harnesses. Full steps: \`results/traces/<run id>/\`.`,
  "",
  "## Outcome and cost",
  "",
  table([
    head,
    across("Run", (run) => run.row.run_id),
    across("Route", (run) => run.row.route),
    across("Hidden tests passed", (run) => `${run.row.hidden_pass || 0} of ${run.row.hidden_total}`),
    across("Visible tests exit", (run) => run.row.visible_exit),
    across("Test files edited", (run) => run.row.test_files_edited || "none"),
    across("Files changed", (run) => run.row.files_changed),
    across("Committed / pushed", (run) => `${run.row.committed} / ${run.row.pushed}`),
    across("Minutes", (run) => (Number(run.row.wall_seconds) / 60).toFixed(1)),
    across("Stopped by itself", (run) => run.row.stopped_cleanly),
    across("Ending", (run) => run.summary.ending?.reason),
    across("Cost", (run) => `${money(run.row.cost_usd)} (${run.row.cost_source})`),
    // Codex's input count includes the cached and cache-written tokens; the others' doesn't.
    across("Uncached input tokens", (run) => (run.condition === "codex" ? Number(run.row.input_tokens) - Number(run.row.cached_tokens) - Number(run.row.cache_write_tokens) : run.row.input_tokens)),
    across("Cached input tokens", (run) => run.row.cached_tokens),
    across("Cache-write tokens", (run) => run.row.cache_write_tokens),
    across("Output tokens, as logged", (run) => run.row.output_tokens),
    across("Reasoning tokens", (run) => reasoningTokens(run)),
    across("Model requests", (run) => run.summary.requests),
    across("Peak context tokens", (run) => run.summary.peakContextTokens),
  ]),
  "",
  "## How it worked",
  "",
  table([
    head,
    across("Tool calls", (run) => run.summary.toolCalls),
    across("Tools used", (run) => Object.entries(run.summary.toolsUsed).map(([name, count]) => `${name} ${count}`).join(", ")),
    across("Shell commands", (run) => run.summary.commands),
    across("Test runs", (run) => run.summary.testRuns.length),
    across("Characters of tool output returned to the model", (run) => run.summary.outputCharsReturnedToModel),
    across("Blocked steps", (run) => run.summary.blocked.length),
    across("Messages to the user", (run) => run.summary.said),
    across("Reasoning blocks (with visible text)", (run) => `${run.summary.reasoning.blocks} (${run.summary.reasoning.withVisibleText})`),
    across("Outside paths named (pattern match, read before trusting)", (run) => list(run.summary.outsidePathsTouched)),
  ]),
  "",
  "## Files",
  "",
  "Running the project's tests imports its files, so a disk read doesn't mean the model saw the file.",
  "",
  table([
    head,
    across("Read through a tool", (run) => run.summary.filesReadThroughATool.length),
    across("Edited through a tool", (run) => run.summary.filesEditedThroughATool.length),
    across("Named in shell commands", (run) => run.summary.filesNamedInShellCommands.length),
    across("Created on disk", (run) => list(run.summary.disk.created)),
    across("Modified on disk", (run) => run.summary.disk.modified?.length),
    across("Deleted on disk", (run) => list(run.summary.disk.deleted)),
    across("Read on disk, of files it left unchanged", (run) => (run.summary.disk.inventoried ? `${run.summary.disk.unchangedAndReadOnDisk} of ${run.summary.disk.unchangedFiles}` : "not recorded")),
    across("Unchanged and never read on disk", (run) => list(run.summary.disk.neverReadOnDisk)),
    across("Read on disk, but no tool or command shows it", (run) => list(run.summary.disk.readOnDiskButNotThroughATool)),
  ]),
  "",
  "## Test results over time",
  "",
  "From the agent's own test runs: pass/fail at each run, in order.",
  "",
  table([head, across("Runs", (run) => run.summary.testRuns.map((test) => (test.pass == null ? `exit ${test.exit}` : `${test.pass}/${test.fail}`)).join(" → ") || "none")]),
  "",
  "## Hidden tests failed, by area",
  "",
]

const areaOf = (name) => (name.includes(":") ? name.split(":")[0] : "other")
const areas = [...new Set(runs.flatMap((run) => run.failing.map(areaOf)))].sort()
lines.push(areas.length ? table([head, ...areas.map((area) => [area, ...runs.map((run) => run.failing.filter((name) => areaOf(name) === area).length)])]) : "No hidden test failed in any run.", "")

for (const run of runs) {
  lines.push(`## ${run.condition}: details`, "")
  lines.push("**Failed hidden tests**", "", run.failing.length ? run.failing.map((name) => `- ${name}`).join("\n") : "None.", "")
  const blocked = run.summary.blocked
  lines.push("**Blocked steps**", "", blocked.length ? blocked.map((item) => `- Step ${item.seq}, ${item.tool}, ${item.by}: ${String(item.message ?? "").replace(/\s+/g, " ").slice(0, 240)}`).join("\n") : "None.", "")
  const order = run.files.filter((file) => Number(file.read) > 0).slice(0, 15).map((file) => file.path)
  lines.push("**First files read through a tool**", "", order.length ? order.map((path) => `\`${path}\``).join(", ") : "None.", "")
  lines.push("**What it told the user at the end**", "", run.summary.finalText ? run.summary.finalText.split("\n").map((line) => `> ${line}`).join("\n") : "Nothing recorded.", "")
}

// What each harness put in front of the model before any work, from -CaptureRequests.
const captureDir = join(lab, "results", "first-requests", `level-${level}`)
const firstRequest = (name) => {
  const path = join(captureDir, `${name}.jsonl`)
  if (!existsSync(path)) return null
  const requests = readFileSync(path, "utf8").split("\n").filter(Boolean).map((line) => JSON.parse(line))
  return requests.find((request) => request.body?.tools)?.body ?? null
}
const captured = [["Claude Code", "claude"], ["OpenCode", "opencode"], ["Codex, as sent", "codex"], ["Codex, after LiteLLM", "codex-after-gateway"]].map(([label, name]) => [label, firstRequest(name)]).filter(([, body]) => body)
if (captured.length) {
  const chars = (value) => (value == null ? 0 : (typeof value === "string" ? value : JSON.stringify(value)).length)
  const systemOf = (body) => (typeof body.system === "string" ? body.system : (body.system ?? []).map((part) => part.text).join("\n"))
  const toolName = (tool) => tool.name ?? tool.type
  lines.push("## What each harness sends first", "", "Recorded with no model behind the address, with the same task. Character counts, not tokens. Codex's instructions are in its input, not a system field.", "")
  lines.push(
    table([
      ["", ...captured.map(([label]) => label)],
      ["System prompt characters", ...captured.map(([, body]) => systemOf(body).length)],
      ["Messages or input characters", ...captured.map(([, body]) => chars(body.messages ?? body.input))],
      ["Tools offered", ...captured.map(([, body]) => body.tools.length)],
      ["Tool definition characters", ...captured.map(([, body]) => chars(body.tools))],
      ["Tool names", ...captured.map(([, body]) => body.tools.map(toolName).join(", "))],
      ["Thinking", ...captured.map(([, body]) => JSON.stringify(body.thinking ?? "not set"))],
      ["Effort", ...captured.map(([, body]) => body.output_config?.effort ?? body.reasoning?.effort ?? "not set")],
    ]),
    "",
  )
}

const out = join(lab, "results", `level-${level}-comparison.md`)
writeFileSync(out, lines.join("\n"))
console.log(`Wrote ${out}`)
